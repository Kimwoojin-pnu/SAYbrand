def get_all_keywords() -> list[tuple[str, str, float, bool, bool]]:
    """
    모든 키워드를 플랫 리스트로 반환
    Returns: [(keyword, category, weight, requires_brand, auto_critical)]
    """
    result = []
    for cat_name, cat_data in KEYWORD_DATABASE.items():
        for kw in cat_data["keywords"]:
            result.append((
                kw,
                cat_data["category"],
                cat_data["weight"],
                cat_data.get("requires_brand", False),
                cat_data.get("auto_critical", False),
            ))
    return result


def get_stats() -> dict:
    total = sum(len(v["keywords"]) for v in KEYWORD_DATABASE.values())
    by_module = {}
    for cat_data in KEYWORD_DATABASE.values():
        m = cat_data["category"]
        by_module[m] = by_module.get(m, 0) + len(cat_data["keywords"])
    return {
        "total_keywords": total,
        "categories": len(KEYWORD_DATABASE),
        "by_module": by_module,
        "negative_filters": len(NEGATIVE_KEYWORD_LIST),
    }


